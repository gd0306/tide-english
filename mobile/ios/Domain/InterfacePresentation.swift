        guard language == .chinese else { return english }
        if let translated = chinese[english] { return translated }
        for template in templates {
            if let translated = template.render(english) { return translated }
        }
        // Only localize a reference suffix when its complete preceding message is known.
        if let marker = english.range(of: "\n\nReference: ", options: .backwards) {
            let detail = String(english[..<marker.lowerBound])
            let reference = String(english[marker.upperBound...])
            if !reference.isEmpty, !reference.contains(where: { $0.isNewline }) {
                let translated = string(detail, language: language)
                if translated != detail { return translated + "\n\n参考编号：" + reference }
            }
        }
        return english
    }

