import Foundation

public enum InterfaceTheme: String, CaseIterable, Codable, Sendable {
    case paper, midnight, grove
}

public enum InterfaceLanguage: String, CaseIterable, Codable, Sendable {
    case chinese, english
}

/// Presentation preferences are independent of provider credentials and learning data.
public struct InterfaceConfiguration: Equatable, Sendable {
    public var theme: InterfaceTheme
    public var language: InterfaceLanguage

    public init(theme: InterfaceTheme, language: InterfaceLanguage) {
        self.theme = theme
        self.language = language
    }

    public static func restored(theme: String?, language: String?, preferredLanguages: [String]) -> Self {
        let systemLanguage = preferredLanguages.lazy.compactMap { identifier -> InterfaceLanguage? in
            let primary = identifier.lowercased().split(whereSeparator: { $0 == "-" || $0 == "_" }).first
            switch primary {
            case "zh": return .chinese
            case "en": return .english
            default: return nil
            }
        }.first ?? .english
        return Self(theme: theme.flatMap(InterfaceTheme.init(rawValue:)) ?? .paper,
                    language: language.flatMap(InterfaceLanguage.init(rawValue:)) ?? systemLanguage)
    }
}

