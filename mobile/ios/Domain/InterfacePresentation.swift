    /// Literal surroundings and whole-string anchors prevent substring translation.
    /// Numeric slots accept only nonnegative ASCII integers; other slots preserve
    /// one-line values. Insertions never pass through another replacement step.
    private struct Template: Sendable {
        let expression: NSRegularExpression
        let output: String
        let localizedCaptures: Set<Int>
        let allowedCaptures: [Int: Set<String>]

        init(_ source: String, _ output: String, localizedCaptures: Set<Int> = [], allowedCaptures: [Int: Set<String>] = [:]) {
            let placeholders = Self.placeholder.matches(in: source, range: NSRange(source.startIndex..., in: source))
            var cursor = source.startIndex
            var pattern = "\\A"
            for placeholder in placeholders {
                guard let range = Range(placeholder.range, in: source) else { continue }
                pattern += NSRegularExpression.escapedPattern(for: String(source[cursor..<range.lowerBound]))
                pattern += placeholder.range(at: 2).location == NSNotFound ? "([^\\r\\n]+?)" : "([0-9]+)"
                cursor = range.upperBound
            }
            pattern += NSRegularExpression.escapedPattern(for: String(source[cursor...])) + "\\z"
            expression = try! NSRegularExpression(pattern: pattern)
            self.output = output
            self.localizedCaptures = localizedCaptures
            self.allowedCaptures = allowedCaptures
        }

        func render(_ input: String) -> String? {
            guard let match = expression.firstMatch(in: input, range: NSRange(input.startIndex..., in: input)) else { return nil }
            var values: [Int: String] = [:]
            for index in 1..<match.numberOfRanges {
                guard let range = Range(match.range(at: index), in: input) else { return nil }
                let value = String(input[range])
                if let allowed = allowedCaptures[index], !allowed.contains(value) { return nil }
                if localizedCaptures.contains(index) {
                    let translated = InterfaceText.string(value, language: .chinese)
                    guard translated != value else { return nil }
                    values[index] = translated
                } else {
                    values[index] = value
                }
            }
            var result = ""
            var cursor = output.startIndex
            for placeholder in Self.placeholder.matches(in: output, range: NSRange(output.startIndex..., in: output)) {
                guard let range = Range(placeholder.range, in: output),
                      let indexRange = Range(placeholder.range(at: 1), in: output),
                      let index = Int(output[indexRange]), let value = values[index] else { return nil }
                result += output[cursor..<range.lowerBound]
                result += value
                cursor = range.upperBound
            }
            result += output[cursor...]
            return result
        }

        private static let placeholder = try! NSRegularExpression(pattern: "\\{([0-9]+)(#)?\\}")
    }
